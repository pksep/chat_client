export const VOICE_FAREWELL_REPLY = 'До свидания! Буду рад помочь снова.';

const courtesy =
  '(?:ну|все|ладно|хорошо|тогда|давай|давайте|ага|окей|ок|пожалуйста|спасибо(?: большое)?(?: тебе| вам)?(?: за помощь)?|сэпи|сепи|ассистент)';

const farewell = new RegExp(
  `^(?:${courtesy}\\s+)*(?:` +
    'пока(?:\\s?пока)?|до\\s?свидания|до встречи|до связи|до завтра|до скорого|до новых встреч|' +
    'всего хорошего|всего доброго|хорошего дня|спокойной ночи|увидимся|прощай(?:те)?|' +
    'бай(?:\\s?бай)?|на этом (?:все|закончим|заканчиваем)|(?:закончим|заканчиваем) на этом|отключайся|' +
    '(?:на этом\\s+)?(?:закончим|заверши(?:ть|м)?|завершай|закрой|закончи|заканчивай)' +
    '(?:\\s+(?:этот|наш))?\\s+(?:разговор|звонок|сеанс|голосовой режим)' +
    `)(?:\\s+${courtesy})*$`,
  'u'
);

/** Команда должна занимать всю реплику: «пока не закрывай» не является прощанием. */
export function isVoiceFarewell(text: string): boolean {
  const normalized = text
    .normalize('NFKC')
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  return normalized.length <= 220 && farewell.test(normalized);
}
